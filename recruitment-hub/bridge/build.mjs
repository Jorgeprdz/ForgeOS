import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const EXPORTS = Object.freeze({
  evaluateInterviewFlow: ['manager-os/recruitment/interview-flow/interview-flow-engine.js','evaluateInterviewFlow'],
  normalizeInterviewStage: ['manager-os/recruitment/interview-flow/interview-flow-engine.js','normalizeInterviewStage'],
  evaluateRecruitmentPipeline: ['manager-os/recruitment/pipeline/recruitment-pipeline-engine.js','evaluateRecruitmentPipeline'],
  normalizeRecruitmentPipelineState: ['manager-os/recruitment/pipeline/recruitment-pipeline-engine.js','normalizeRecruitmentPipelineState'],
  captureManagerRecruitmentEvent: ['manager-os/recruitment/events/manager-recruitment-event-capture-contract.js','captureManagerRecruitmentEvent'],
  buildCandidateManagerSnapshot: ['manager-os/recruitment/snapshots/candidate-manager-snapshot-engine.js','buildCandidateManagerSnapshot'],
  calculateManagerRecruitmentMetrics: ['manager-os/metrics/manager-recruitment-metrics-engine.js','calculateManagerRecruitmentMetrics']
});
const sha = value => createHash('sha256').update(value).digest('hex');
export function buildBundle({ root = ROOT } = {}) {
  const original = JSON.parse(readFileSync(resolve(root,'recruitment-hub/bridge/source-manifest.json'),'utf8'));
  const sources = [...original.sources].sort((a,b) => a.path.localeCompare(b.path, 'en'));
  const allowed = new Set(Object.values(EXPORTS).map(([path]) => path));
  if (sources.length !== 5 || sources.some(s => !allowed.has(s.path)) || new Set(sources.map(s => s.path)).size !== 5) throw new Error('SOURCE_ALLOWLIST');
  const factories = sources.map(source => {
    let text = readFileSync(resolve(root,source.path),'utf8');
    if (sha(text) !== source.sha256) throw new Error('SOURCE_INTEGRITY');
    text = text.replace(/\brequire\(\s*(['"])([^'"]+)\1\s*\)/g, (_match,_quote, request) => {
      const path = posix.normalize(posix.join(posix.dirname(source.path),request)) + (request.endsWith('.js') ? '' : '.js');
      if (!request.startsWith('.') || !allowed.has(path)) throw new Error('DEPENDENCY_NOT_ALLOWED');
      return `__require(${JSON.stringify(path)})`;
    });
    return `${JSON.stringify(source.path)}: (module, exports, __require) => {\n${text}\n}`;
  });
  const code = '// Generated by rh-2b-deterministic-cjs-linker-v1. Do not edit.\n' +
    `const __factories = {\n${factories.join(',\n')}\n};\n` +
    'const __cache = Object.create(null);\nfunction __require(id) {\n' +
    '  if (!Object.hasOwn(__factories, id)) throw new Error("DEPENDENCY_NOT_ALLOWED");\n' +
    '  if (__cache[id]) return __cache[id].exports;\n  const module = { exports: {} };\n' +
    '  __cache[id] = module;\n  __factories[id](module, module.exports, __require);\n  return module.exports;\n}\n' +
    Object.entries(EXPORTS).map(([name,[path,member]]) => `export const ${name} = __require(${JSON.stringify(path)}).${member};`).join('\n') + '\n';
  const manifest = { schemaVersion: 2, generator: 'rh-2b-deterministic-cjs-linker-v1',
    sourceRepository: original.sourceRepository, commit: original.commit, sources,
    originalBundleSha256: original.originalBundleSha256, bundlePath: 'recruitment-hub/src/generated/forge-recruitment.mjs',
    bundleSha256: sha(code), namedExports: Object.keys(EXPORTS).sort(), excludedLegacyProvenance: true };
  return { code, manifest };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { code, manifest } = buildBundle();
  const target = resolve(ROOT, manifest.bundlePath);
  const manifestPath = resolve(ROOT,'recruitment-hub/bridge/migration-manifest.json');
  const json = JSON.stringify(manifest,null,2) + '\n';
  if (process.argv[2] === '--check') {
    if (readFileSync(target,'utf8') !== code || readFileSync(manifestPath,'utf8') !== json) throw new Error('BUNDLE_NOT_REPRODUCIBLE');
    console.log('SAFE_BUNDLE_REPRODUCIBLE=PASS');
  } else if (process.argv[2] === '--write') {
    mkdirSync(dirname(target),{ recursive: true }); writeFileSync(target,code); writeFileSync(manifestPath,json);
    console.log(`SAFE_BUNDLE_SHA256=${manifest.bundleSha256}`);
  } else throw new Error('USE_--write_OR_--check');
}
